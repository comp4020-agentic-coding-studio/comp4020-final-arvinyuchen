// The places Spots starts with, so a new group has something to explore
// before anyone has added their own, and so a search for most things a group
// might want ("mexican food", "bowling", "a swim") finds something. A group's
// own finds go alongside these (see addCustomPick in db.ts), and those are
// the ones that make a list theirs.
//
// The first twelve were checked against their Wikipedia articles
// (`source`) for name, suburb and every claim in the blurb, with
// coordinates from the article or OpenStreetMap's Nominatim, and Commons
// photos under the licence named, hotlinked as 800px thumbnails and
// credited on the card with a link to the file page (what CC BY and CC
// BY-SA ask for).
//
// The rest were chosen for breadth, one for each kind of thing people look
// for (a cuisine, coffee or tea, a bar, an activity, a walk, a stage) and
// spread across the suburbs. Each was recommended by the editorial source
// it cites (a local guide or paper, VisitCanberra, ACT Parks, Wikipedia),
// with evidence it was still open in 2025–26; its blurb claims nothing that
// source doesn't. Coordinates are Overture's or OpenStreetMap's. Their
// pictures are illustrations made for Spots (`public/places/`): a dish for
// food and drink, what you do there for the rest, never the venue itself,
// and the card says "Illustration" so it isn't taken for a photo.
//
// These are only the seed: on boot they're upserted into the shared `places`
// table (src/lib/db.ts), where every place any group adds joins them.
